export const STRINGS = { en, sk };

/** The language to show: the one the user picked, else Slovak on a Slovak phone, else English. */
export function pickLanguage(saved, phone) {
  if (saved === "en" || saved === "sk") return saved;
  return /^sk\b/i.test(String(phone || "")) ? "sk" : "en";
}

/** The locale for dates and times: the phone's own when it is in that language. */
export function localeFor(lang, phone) {
  const p = String(phone || "");
  if (lang === "sk") return /^sk\b/i.test(p) ? p : "sk-SK";
  return /^en\b/i.test(p) ? p : "en-GB";
}

/** A function that gives a text in `lang`, with its plural form and values filled in. */
export function translator(lang) {
  const table = STRINGS[lang] || en;
  let rules;
  try {
    rules = new Intl.PluralRules(lang === "sk" ? "sk" : "en");
  } catch {
    rules = { select: (n) => (n === 1 ? "one" : "other") };
  }
  return (key, params = {}) => {
    let message = table[key] !== undefined ? table[key] : en[key] !== undefined ? en[key] : key;
    if (typeof message === "object") {
      const n = Number(params.n);
      message = (n === 0 && message.zero) || message[rules.select(n)] || message.other;
    }
    return message.replace(/\{(\w+)\}/g, (whole, name) => (params[name] !== undefined ? String(params[name]) : whole));
  };
}
