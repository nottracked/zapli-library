export const STRINGS = { en, sk };

/** The app's language: the one picked in Settings, else Slovak on a Slovak phone, else English. */
export function pickLanguage(choice, phone) {
  if (choice === "en" || choice === "sk") return choice;
  return /^sk\b/i.test(String(phone || "").replace("_", "-")) ? "sk" : "en";
}

/** The locale for numbers and dates: Slovak formats for Slovak; for English the phone's own English, else British. */
export function localeFor(lang, phone) {
  if (lang === "sk") return "sk-SK";
  const tag = String(phone || "").replace("_", "-");
  return /^en-[A-Z]{2}$/i.test(tag) ? tag : "en-GB";
}

/** A plural choice inside a text: "{n, plural, one {# day} other {# days}}". */
function plurals(text, params, rules) {
  return text.replace(/\{(\w+), plural, ((?:[a-z=0-9]+ \{[^{}]*\}\s*)+)\}/g, (all, name, forms) => {
    const n = Number(params[name]);
    const options = {};
    for (const m of forms.matchAll(/([a-z=0-9]+) \{([^{}]*)\}/g)) options[m[1]] = m[2];
    const form = options["=" + n] ?? options[rules.select(n)] ?? options.other ?? "";
    return form.replace(/#/g, String(n));
  });
}

/** The translate function of a language: t(key, params). A missing text falls back to English, then to its key. */
export function translator(lang) {
  const table = STRINGS[lang] || en;
  const rules = new Intl.PluralRules(lang === "sk" ? "sk" : "en");
  return (key, params = {}) => {
    let message = table[key] ?? en[key];
    if (message === undefined) return key;
    if (typeof message === "object") {
      const n = Number(params.n);
      message = (n === 0 && message.zero) || message[rules.select(n)] || message.other;
    }
    if (message.includes(", plural,")) message = plurals(message, params, rules);
    return message.replace(/\{(\w+)\}/g, (all, name) => (params[name] !== undefined ? String(params[name]) : all));
  };
}
