export const STRINGS = { en: EN, sk: SK };
export const LANGUAGES = ["en", "sk"];

/** The language the page speaks: the user's choice, else the phone's when it is Slovak (or Czech), else English. */
export function pickLanguage(choice, phone) {
  if (choice === "en" || choice === "sk") return choice;
  const lang = String(phone || "").toLowerCase();
  return lang.startsWith("sk") || lang.startsWith("cs") ? "sk" : "en";
}

/** Which plural form `n` takes in `lang`. */
export function pluralForm(lang, n) {
  if (lang === "sk") {
    if (n === 1) return "one";
    if (Number.isInteger(n) && n >= 2 && n <= 4) return "few";
    return "other";
  }
  return n === 1 ? "one" : "other";
}

/** A function that reads a message in `lang` and fills in its values; English stands in for a missing text. */
export function translator(lang) {
  const table = STRINGS[lang] || EN;
  return (key, values = {}) => {
    let message = table[key] ?? EN[key] ?? key;
    if (typeof message === "object") {
      const form = pluralForm(lang, Number(values.n));
      message = message[form] ?? message.other;
    }
    return message.replace(/\{(\w+)\}/g, (m, name) => (values[name] === undefined ? m : String(values[name])));
  };
}
